CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(60) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT app_users_normalized_email CHECK (email = lower(email) AND email = btrim(email)),
    CONSTRAINT app_users_bcrypt_hash CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);

-- Do not invent ownership for existing orders. Only ADMIN can access legacy NULL owners.
ALTER TABLE customer_orders ADD COLUMN user_id BIGINT REFERENCES app_users(id) ON DELETE RESTRICT;
CREATE INDEX idx_customer_orders_user_id ON customer_orders(user_id) WHERE user_id IS NOT NULL;

ALTER TABLE order_idempotency ADD COLUMN user_id BIGINT REFERENCES app_users(id) ON DELETE RESTRICT;
ALTER TABLE order_idempotency ADD COLUMN id BIGINT GENERATED ALWAYS AS IDENTITY;
ALTER TABLE order_idempotency DROP CONSTRAINT order_idempotency_pkey;
ALTER TABLE order_idempotency ADD PRIMARY KEY (id);
CREATE UNIQUE INDEX uk_order_idempotency_user_key ON order_idempotency(user_id, idempotency_key) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uk_order_idempotency_legacy_key ON order_idempotency(idempotency_key) WHERE user_id IS NULL;

-- Check the exact reservation, since different users can now use the same client key.
CREATE OR REPLACE FUNCTION ensure_order_idempotency_completed() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    incomplete BOOLEAN;
BEGIN
    EXECUTE format('SELECT EXISTS (SELECT 1 FROM %s WHERE id = $1 AND order_id IS NULL)', TG_RELID::regclass)
        INTO incomplete USING NEW.id;
    IF incomplete THEN
        RAISE EXCEPTION 'Cannot commit an incomplete order idempotency reservation' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
