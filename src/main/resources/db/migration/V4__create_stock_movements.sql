-- New journal only. Existing products/orders are deliberately not backfilled.
CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    movement_type VARCHAR(30) NOT NULL,
    quantity_delta INTEGER NOT NULL,
    stock_before INTEGER NOT NULL CHECK (stock_before >= 0),
    stock_after INTEGER NOT NULL CHECK (stock_after >= 0),
    reference_order_id BIGINT REFERENCES customer_orders(id) ON DELETE RESTRICT,
    reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_stock_movement_balance CHECK (stock_before::BIGINT + quantity_delta::BIGINT = stock_after::BIGINT),
    CONSTRAINT ck_stock_movement_type CHECK (
        (movement_type = 'INITIAL_STOCK' AND quantity_delta >= 0 AND stock_before = 0
            AND reference_order_id IS NULL AND reason IS NULL)
        OR (movement_type = 'ORDER_DEDUCTION' AND quantity_delta < 0
            AND reference_order_id IS NOT NULL AND reason IS NULL)
        OR (movement_type = 'ORDER_CANCELLATION' AND quantity_delta > 0
            AND reference_order_id IS NOT NULL AND reason IS NULL)
        OR (movement_type = 'MANUAL_RESTOCK' AND quantity_delta > 0
            AND reference_order_id IS NULL AND reason IS NOT NULL AND length(btrim(reason)) > 0)
    )
);

CREATE INDEX idx_stock_movements_product_time ON stock_movements(product_id, created_at DESC, id DESC);
-- At most one opening entry and one deduction/cancellation per order/product.
CREATE UNIQUE INDEX uk_stock_movements_initial ON stock_movements(product_id) WHERE movement_type = 'INITIAL_STOCK';
CREATE UNIQUE INDEX uk_stock_movements_order_product_type
    ON stock_movements(reference_order_id, product_id, movement_type) WHERE reference_order_id IS NOT NULL;
